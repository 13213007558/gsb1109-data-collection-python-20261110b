"""Optional source-location tracking for the HTML parser.

The tokenizer and tree builder only see the *normalized* input: the declared
encoding has been applied and CR / CR LF line endings have been converted to
LF.  The classes in this module record where the nodes of the final tree came
from in that normalized input, so that an auditing tool can map a node back to
the corresponding region of the original document.

The feature is opt-in (``HTMLParser(source_locator=True)``) and is completely
inert otherwise, so the default parsing behaviour and performance is
unchanged.
"""

from __future__ import absolute_import, division, unicode_literals


# Origin constants.  They are deliberately strings rather than an ``enum`` so
# that the public API stays simple and works on every supported Python version.

#: The node corresponds to markup or characters that were present verbatim in
#: the (normalized) input.
SOURCE_ORIGIN_PRESENT = "present"

#: The node was generated by the parser during error recovery and has no
#: corresponding markup in the input (e.g. an implied ``<html>``/``<head>``/
#: ``<body>`` or a reconstructed active formatting element).
SOURCE_ORIGIN_IMPLIED = "implied"


class SourceLocation(object):
    """A pointer to a region of the normalized input stream.

    All coordinates refer to the input *after* encoding and newline
    normalization (see :class:`~html5lib._sourcelocator.SourceLocator` for the
    exact rules).  They do **not** point into the raw bytes of an un-decoded
    document.

    :ivar startOffset: zero-based character offset of the first character of
        the region in the normalized stream.
    :ivar endOffset: zero-based character offset one past the last character
        (the region is the half-open range ``[startOffset, endOffset)``).
    :ivar startLine: one-based line number of the first character.
    :ivar startColumn: zero-based column of the first character within its
        line.
    :ivar endLine: one-based line number of the last character.
    :ivar endColumn: zero-based column one past the last character within its
        line.
    """

    __slots__ = ("startOffset", "endOffset", "startLine", "startColumn",
                 "endLine", "endColumn")

    def __init__(self, startOffset, endOffset, startLine, startColumn,
                 endLine, endColumn):
        self.startOffset = startOffset
        self.endOffset = endOffset
        self.startLine = startLine
        self.startColumn = startColumn
        self.endLine = endLine
        self.endColumn = endColumn

    def __repr__(self):
        return ("SourceLocation(offset=%d..%d, line=%d col=%d .. line=%d "
                "col=%d)" % (self.startOffset, self.endOffset,
                             self.startLine, self.startColumn,
                             self.endLine, self.endColumn))

    def __eq__(self, other):
        if not isinstance(other, SourceLocation):
            return NotImplemented
        return (self.startOffset == other.startOffset and
                self.endOffset == other.endOffset and
                self.startLine == other.startLine and
                self.startColumn == other.startColumn and
                self.endLine == other.endLine and
                self.endColumn == other.endColumn)

    def __ne__(self, other):
        result = self.__eq__(other)
        if result is NotImplemented:
            return result
        return not result

    def __hash__(self):
        return hash((self.startOffset, self.endOffset, self.startLine,
                     self.startColumn, self.endLine, self.endColumn))


class SourceRange(object):
    """A contiguous run of normalized characters backing part of a node.

    Text nodes are frequently assembled from several separate character
    tokens (for example whitespace and non-whitespace tokens, or characters
    split across the boundaries of table foster parenting).  Each :class:`SourceRange`
    records one such run; a text node whose content came from a single token
    has a single range.

    :ivar location: the location of the run.
    :ivar text: the normalized characters covered by :attr:`location`.
    """

    __slots__ = ("location", "text")

    def __init__(self, location, text):
        self.location = location
        self.text = text

    def __repr__(self):
        return "SourceRange(%r, %r)" % (self.location, self.text)

    def __eq__(self, other):
        if not isinstance(other, SourceRange):
            return NotImplemented
        return self.location == other.location and self.text == other.text

    def __ne__(self, other):
        result = self.__eq__(other)
        if result is NotImplemented:
            return result
        return not result


class SourceInfo(object):
    """Provenance information attached to a single output node.

    Every element, comment and doctype node that exists while source tracking
    is enabled gets a :class:`SourceInfo`, including parser-generated ones, so
    callers can always tell *why* a node is there.  Text is stored differently
    (an etree/DOM element keeps its text as ``.text``/``.tail`` rather than as
    a node), so the ranges of an element's text are returned separately by
    :meth:`SourceLocator.textRangesOf`.

    :ivar origin: :data:`SOURCE_ORIGIN_PRESENT` for content that was in the
        input, or :data:`SOURCE_ORIGIN_IMPLIED` for nodes the parser generated.
    :ivar location: the :class:`SourceLocation` of the node, or :obj:`None` for
        an implied node.  For elements this spans the whole tag; for comments
        the comment (including the delimiters); for doctypes the doctype
        declaration.
    :ivar implied: convenience flag, equivalent to
        ``origin == SOURCE_ORIGIN_IMPLIED``.
    """

    __slots__ = ("origin", "location")

    def __init__(self, origin, location=None):
        self.origin = origin
        self.location = location

    @property
    def implied(self):
        return self.origin == SOURCE_ORIGIN_IMPLIED

    def __repr__(self):
        if self.implied:
            return "SourceInfo(origin=implied)"
        return "SourceInfo(origin=present, location=%r)" % (self.location,)


class SourceLocator(object):
    """Builds and stores the :class:`SourceInfo` for every output node.

    Coordinate conventions
    ----------------------
    All offsets and line/column numbers describe the **normalized** character
    stream that the tokenizer consumes, not the raw source bytes:

    * The stream is decoded using the encoding that the parser settles on
      (BOM, transport/override encoding, ``<meta charset>`` or default).  Byte
      offsets from before decoding are therefore not represented; use the
      character offsets against the decoded text.
    * Leading byte-order marks are consumed by the encoding sniffing stage and
      are not part of the tracked stream.
    * Carriage returns are normalized before tracking: a ``CR LF`` sequence and
      a lone ``CR`` each become a single ``LF``.  Consequently a line is always
      terminated by ``LF``, line numbers count ``LF`` characters, and a Windows
      or classic-Mac document maps to the same coordinates as its LF-normalized
      form.  Offsets count the normalized characters, so they are shorter than
      the raw byte/character count when CR characters were removed.
    * Offsets are zero-based character (code point) indices; line numbers are
      one-based; columns are zero-based character columns within a line,
      measured from the end of the preceding ``LF``.
    * Surrogate pairs and combining marks count as their individual code
      points, i.e. one offset per code point, not per user-perceived character.

    Given a location, the matching region of the original page is the same
    region after inverting the encoding and line-ending normalization, which is
    sufficient to place a cursor or highlight even when the parser moved the
    node (for example table foster parenting).
    """

    def __init__(self, stream):
        self._stream = stream
        # Maps the in-memory node object returned by the tree builder (the
        # etree Element, DOM node, ...) to its SourceInfo.
        self._sources = {}
        # Maps an element node to the ordered list of SourceRange objects that
        # make up its direct textual content (its text and the tails inserted
        # directly under it).  Kept separate from _sources because an element
        # can be parser-generated while still containing real input text, or
        # vice versa.
        self._textRanges = {}

    def reset(self):
        """Clear all recorded provenance.

        Used when an encoding change forces the input to be reparsed: the
        stream is rewound and the tree rebuilt, so information from the
        abandoned pass must not survive.
        """
        self._sources = {}
        self._textRanges = {}

    # -- token helpers -----------------------------------------------------

    def tokenLocation(self, token):
        """Return the :class:`SourceLocation` recorded on a token, if any."""
        meta = token.get("source")
        if meta is None:
            return None
        return self._location(meta["startOffset"], meta["endOffset"])

    def _location(self, startOffset, endOffset):
        startLine, startColumn = self._stream.lineColAt(startOffset)
        endLine, endColumn = self._stream.lineColAt(endOffset)
        return SourceLocation(startOffset, endOffset,
                              startLine, startColumn,
                              endLine, endColumn)

    # -- node registration -------------------------------------------------

    def _put(self, node, info):
        if node is not None:
            self._sources[id(node)] = info
        return node

    def present(self, node, token):
        """Record ``node`` as coming from the markup in ``token``."""
        location = self.tokenLocation(token)
        info = SourceInfo(SOURCE_ORIGIN_PRESENT, location)
        return self._put(node, info)

    def addText(self, node, token, data):
        """Record a fragment of an element's direct text.

        An element's text may be produced by several character tokens (notably
        when whitespace tokens are emitted separately or when table foster
        parenting moves characters around); each call appends one
        :class:`SourceRange` to that element's list.  The ranges are kept
        independently of the element's own :class:`SourceInfo`, so a
        parser-generated element (e.g. an implied ``<body>``) can still carry
        real input text.

        A token without a recorded span (a token synthesized during error
        recovery) contributes no range and is ignored.
        """
        location = self.tokenLocation(token)
        if location is None:
            return
        ranges = self._textRanges.get(id(node))
        if ranges is None:
            ranges = []
            self._textRanges[id(node)] = ranges
        ranges.append(SourceRange(location, data))

    def implied(self, node):
        """Record ``node`` as parser-generated, with no source markup."""
        return self._put(node, SourceInfo(SOURCE_ORIGIN_IMPLIED))

    def clone(self, node):
        """Record an adoption-agency clone as parser-generated.

        A clone is a new node produced by error recovery rather than markup, so
        it is marked implied even though the element it was copied from was
        present in the input.
        """
        return self._put(node, SourceInfo(SOURCE_ORIGIN_IMPLIED))

    @staticmethod
    def _span(first, second):
        return SourceLocation(
            first.startOffset, second.endOffset,
            first.startLine, first.startColumn,
            second.endLine, second.endColumn)

    # -- public query API --------------------------------------------------

    def sourceOf(self, node):
        """Return the :class:`SourceInfo` for ``node``, or :obj:`None`.

        :obj:`None` means the node was not part of the tracked parse, either
        because source tracking was disabled or because the node was created
        by the caller after parsing.
        """
        return self._sources.get(id(node))

    def isImplied(self, node):
        """Return :obj:`True` if ``node`` was generated by the parser."""
        info = self._sources.get(id(node))
        return info is not None and info.implied

    def locationOf(self, node):
        """Return the :class:`SourceLocation` for ``node``, or :obj:`None`.

        Implied nodes always return :obj:`None`; present nodes return their
        location.  This describes the node's own markup; use
        :meth:`textRangesOf` for the location of an element's textual content.
        """
        info = self._sources.get(id(node))
        if info is None or info.implied:
            return None
        return info.location

    def textRangesOf(self, node):
        """Return the ordered list of :class:`SourceRange` for an element's text.

        A normal text node yields a single range; text assembled from several
        input fragments (for example text split across table foster parenting,
        or whitespace emitted as a separate token) yields one range per
        fragment, each carrying its own location and the exact characters it
        contributed.  Returns an empty list when the element has no recorded
        text.
        """
        return list(self._textRanges.get(id(node), ()))

    def textLocationOf(self, node):
        """Return the :class:`SourceLocation` spanning all of an element's text.

        :obj:`None` when the element has no recorded text; otherwise a location
        from the start of its first fragment to the end of its last fragment.
        """
        ranges = self._textRanges.get(id(node))
        if not ranges:
            return None
        return self._span(ranges[0].location, ranges[-1].location)

    def reparentText(self, fromNode, toNode):
        """Move all recorded text ranges from one element to another.

        Used when the parser moves an element's direct textual content to a
        different element (fragment extraction, or the adoption agency
        algorithm); child elements keep their own provenance and are not
        affected.
        """
        moved = self._textRanges.pop(id(fromNode), None)
        if not moved:
            return
        existing = self._textRanges.get(id(toNode))
        if existing is None:
            self._textRanges[id(toNode)] = list(moved)
        else:
            existing.extend(moved)
